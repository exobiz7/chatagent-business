import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {evaluateB5K} from './bs6g5k-auth-evidence-gate.mjs';
const fixture=JSON.parse(readFileSync('docs/verification/v1.1/B_S6G5K_AUTH_READONLY_EVIDENCE_20261119.json','utf8'));
const blocked=evaluateB5K(fixture);
assert.equal(blocked.result,'BLOCKED_REAL_OAUTH_DEPENDENCIES');
assert.ok(blocked.missing.includes('oauthDiscoveryHttp200'));
assert.ok(blocked.missing.includes('siteUrlActualReadback'));
assert.ok(blocked.missing.includes('resourceAudienceBound'));
assert.ok(blocked.missing.includes('businessWorkspaceE2E'));
assert.equal(blocked.productionCutoverAuthorized,false);
for(const field of ['productionCutoverAuthorized','settingsChangeAuthorized','clientRegistrationAuthorized','externalDeployAuthorized'])assert.equal(blocked[field],false);
const green=structuredClone(fixture);
for(const k of Object.keys(green.verified))green.verified[k]=true;
green.oauthDiscoveryHttpStatus=200;green.clientRegistrationMethod='predefined';
const review=evaluateB5K(green);
assert.equal(review.missing.length,0);
assert.equal(review.result,'EVIDENCE_REQUIRES_INDEPENDENT_OWNER_REVIEW');
assert.equal(review.settingsChangeAuthorized,false);
assert.equal(review.productionCutoverAuthorized,false);
assert.equal(evaluateB5K({...green,clientRegistrationMethod:'cimd'}).result,'BLOCKED_REAL_OAUTH_DEPENDENCIES');
assert.throws(()=>evaluateB5K({...fixture,externalSettingsChanged:true}),/INVALID_GOVERNANCE/);
assert.throws(()=>evaluateB5K({...fixture,productionCutoverAuthorized:true}),/INVALID_GOVERNANCE/);
console.log('PASS B-S6G-5K real evidence missing remains blocked; green hypothetical cannot enable settings');
console.log('PASS B-S6G-5K unknown client mode and governance changes fail closed');
console.log('BUSINESS_BS6G5K_READONLY_ADMISSION=PASS');
