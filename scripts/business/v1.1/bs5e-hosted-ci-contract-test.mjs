import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const repo=fileURLToPath(new URL('../../../',import.meta.url));
const pkg=JSON.parse(readFileSync(`${repo}/package.json`,'utf8'));
const runner=readFileSync(`${repo}/scripts/business/v1.1/run-hosted-ci.mjs`,'utf8');
const full=String(pkg.scripts['test:ci']);
assert.match(full,/npm run test:business:bs3f1/);
assert.match(full,/npm run test:business:bs4a/);
assert.match(full,/npm run test:business:bs4b/);
assert.match(full,/npm run test:business:bs4c/);
assert.match(full,/npm run test:business:bs5a/);
assert.match(full,/npm run test:business:bs5c/);
assert.equal(pkg.scripts['test:ci:hosted'],'node scripts/business/v1.1/run-hosted-ci.mjs');
for(const name of ['bs3f1','bs4a','bs4b','bs4c','bs5a','bs5c'])assert.match(runner,new RegExp(name));
assert.match(runner,/RELEASE_HOST_ONLY/);
assert.match(runner,/spawnSync\('\/bin\/sh',\['-c'/);
assert.doesNotMatch(runner,/\['-lc'/);
console.log('PASS hosted CI derives from full test:ci while replacing only Docker/PostgreSQL effect tests with contract/syntax coverage');
console.log('PASS release-host test:ci retains all Docker/PostgreSQL effect gates');
console.log('BUSINESS_S5E_HOSTED_CI_CONTRACT=PASS');
