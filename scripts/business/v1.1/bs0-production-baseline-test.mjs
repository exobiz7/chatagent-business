import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const repo='/Volumes/SSD 4T/z_proj/proj04_chatagent/chatagent_business';
const prod=process.env.HOME+'/ChatAgentBusiness/production';
const git=(...args)=>execFileSync('git',['-C',repo,...args],{encoding:'utf8'}).trim();
assert.equal(git('rev-list','-n1','v1.0.0'),'d6373f8ffef4b3739134f4d14cc300918417553e','V1_TAG_MOVED');
const release=JSON.parse(readFileSync(prod+'/RELEASE_STATUS.json','utf8'));
assert.equal(release.version,'1.0.0');
assert.equal(release.status,'PRODUCTION_ACTIVE_V1.0.0');
assert.equal(release.releaseCommit,'d6373f8ffef4b3739134f4d14cc300918417553e');
const env={...process.env,CHATAGENT_BUSINESS_OPERATOR_CONFIG:prod+'/operator.json'};
const run=(file)=>JSON.parse(execFileSync(prod+'/app/ops/'+file,[],{encoding:'utf8',env}));
const status=run('Status.command');assert.equal(status.state,'RUNNING');assert.equal(status.healthy,true);
const doctor=run('Doctor.command');assert.equal(doctor.ok,true);assert.ok(doctor.checks.filter(x=>x.required).every(x=>x.ok));
const curl=(url)=>execFileSync('/usr/bin/curl',['-fsS',url],{encoding:'utf8'}).trim();
assert.equal(curl('http://127.0.0.1:51950/healthz'),'live');
assert.equal(curl('http://127.0.0.1:51950/readyz'),'ready');
console.log('PASS Business v1.0 release tag/status/runtime/Doctor/tunnel unchanged');
console.log('B_S0_PRODUCTION_BASELINE=PASS');
